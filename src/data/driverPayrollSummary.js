const normalizeDriver = (value = "") => String(value).trim().toLocaleLowerCase("es");
const payrollByDriver = driverPayrollDocumentSummary.reduce((result, record) => {
  const driverKey = normalizeDriver(record.driver);
  result[driverKey] ??= {};
  result[driverKey][record.period] = record;
  return result;
}, {});

export const driverPayrollByDriver = Object.freeze(payrollByDriver);

export const getImportedPayrollForPeriod = (driver, year, monthIndex) => {
  const period = `${year}-${String(Number(monthIndex) + 1).padStart(2, "0")}`;
  return driverPayrollByDriver[normalizeDriver(driver)]?.[period]?.amount ?? 0;
};
